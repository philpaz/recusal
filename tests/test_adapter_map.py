"""The README's picture of the kernel and its adapters is drawn from the packages, and the
committed files are exactly what the generator prints.

A hand-edited diagram goes stale the day a package is added. This one is generated by
``tools/render_adapter_map.py`` from each adapter's ``pyproject.toml``; these tests hold
the committed SVG files to that output, and hold the drawing itself to the dependency
metadata: a box per adapter, a line to the kernel from every box, an arrow between two
adapters exactly where one requires the other, and nothing drawn out of the kernel.
"""

import importlib.util
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
FILES = ("adapter-map.svg", "adapter-map-light.svg")
SVG = "{http://www.w3.org/2000/svg}"

pytestmark = pytest.mark.skipif(
    sys.version_info < (3, 11), reason="tomllib is in the standard library from Python 3.11"
)


@pytest.fixture(scope="module")
def tool():
    spec = importlib.util.spec_from_file_location(
        "render_adapter_map", ROOT / "tools" / "render_adapter_map.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def found(tool):
    return tool.packages()


def test_the_generator_reads_every_adapter_and_what_it_requires(found):
    on_disk = sorted(
        f"recusal-{p.parent.name}" for p in (ROOT / "adapters").glob("*/pyproject.toml")
    )
    assert sorted(found) == on_disk and len(found) >= 8
    assert found["recusal-langchain"] == ["recusal-langgraph"]
    assert found["recusal-openai-agents-mcp"] == ["recusal-openai-agents"]
    assert found["recusal-langgraph"] == []


@pytest.mark.parametrize("name", FILES)
def test_the_committed_file_is_exactly_what_the_generator_prints(tool, found, name):
    assert (ASSETS / name).read_text(encoding="utf-8") == tool.render(tool.THEMES[name], found), (
        f"assets/{name} is out of date; run python tools/render_adapter_map.py"
    )


def test_the_check_mode_passes_on_the_committed_files_and_fails_on_a_stale_one(
    tool, monkeypatch, tmp_path
):
    assert tool.main(["--check"]) == 0
    for name in FILES:
        (tmp_path / name).write_text((ASSETS / name).read_text(encoding="utf-8"), "utf-8")
    stale = tmp_path / FILES[0]
    stale.write_text(
        stale.read_text(encoding="utf-8").replace("recusal-crewai", "recusal-other"),
        encoding="utf-8",
    )
    monkeypatch.setattr(tool, "ASSETS", tmp_path)
    assert tool.main(["--check"]) == 1


@pytest.mark.parametrize("name", FILES)
def test_the_drawing_is_the_dependency_metadata(tool, found, name):
    root = ET.parse(ASSETS / name).getroot()
    texts = ["".join(node.itertext()) for node in root.iter(f"{SVG}text")]
    # a box, and a label, for every adapter and for nothing else
    labels = [text for text in texts if text.startswith("recusal-")]
    assert sorted(labels) == sorted(found)
    assert "recusal." in texts, "the kernel is drawn once, by name"
    paths = [node.get("d") for node in root.iter(f"{SVG}path") if node.get("fill") == "none"]
    arrows = [
        node.get("d") for node in root.iter(f"{SVG}path") if node.get("marker-end") == "url(#arrow)"
    ]
    requirements = sum(len(required) for required in found.values())
    # one arrow between two adapters per requirement, and one arrow into the kernel
    assert len(arrows) == requirements + 1
    # every adapter has its own line to the bus: a straight one or one routed under its row
    bus = re.search(r"^M(\d+) \d+V\d+$", next(d for d in paths if re.fullmatch(r"M\d+ \d+V\d+", d)))
    assert bus is not None
    to_bus = [d for d in paths if d.endswith(f"H{bus.group(1)}")]
    assert len(to_bus) == len(found)
    # the rows pair an adapter with the one it requires, the dependent on the left
    for left, right, requires in tool.rows(found):
        assert (right in found[left]) is requires


@pytest.mark.parametrize("name", FILES)
def test_the_file_is_a_self_contained_accessible_image(name):
    text = (ASSETS / name).read_text(encoding="utf-8")
    root = ET.fromstring(text)
    assert root.tag == f"{SVG}svg" and root.get("role") == "img"
    assert root.find(f"{SVG}title") is not None and root.find(f"{SVG}desc") is not None
    assert "depends on nothing" in root.find(f"{SVG}desc").text
    # nothing fetched, nothing executed: no script, no link, no embedded resource
    assert not list(root.iter(f"{SVG}script")) and not list(root.iter(f"{SVG}image"))
    assert "href" not in text and "<style" not in text
    assert text.count("http") == 1, "the only URL is the SVG namespace"
    assert "—" not in text


def test_the_readme_shows_both_variants_and_says_in_words_what_the_picture_shows(found):
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    section = readme.split("## The kernel and its adapters\n", 1)[1].split("\n## ", 1)[0]
    raw = "https://raw.githubusercontent.com/philpaz/recusal/main/assets/"
    assert f'srcset="{raw}adapter-map.svg"' in section
    assert f'src="{raw}adapter-map-light.svg"' in section
    alt = re.search(r'<img alt="([^"]+)"', section).group(1)
    for distribution, requires in found.items():
        assert distribution in alt, distribution
        for required in requires:
            assert re.search(rf"{distribution} (also )?(depends )?on {required}", alt) or (
                f"{distribution} on {required}" in alt
            ), (distribution, required)
    assert "The kernel depends on nothing." in alt
    # the README is also the PyPI page, which shows Mermaid as source
    assert "```mermaid" not in readme


def test_the_theme_line_is_the_projects_own(tool, found):
    """The sentence under the picture is the one on the project's seal banner
    (``assets/banner-seal.png``), which puts the constitution's first rule in one line. It
    is not a new slogan, and the rule it restates is still the constitution's first."""
    line = "The thing that generates the work must never certify it."
    for name in FILES:
        assert line in tool.render(tool.THEMES[name], found)
    assert line in (ROOT / "README.md").read_text(encoding="utf-8")
    constitution = (ROOT / "CONSTITUTION.md").read_text(encoding="utf-8")
    assert "### 1. Builders cannot grade their own work" in constitution
    assert (
        "the component that generates an artifact is never the component that\ncertifies it"
        in constitution
    )
    assert (ASSETS / "banner-seal.png").is_file()
