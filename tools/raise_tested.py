"""Raise the framework versions the adapters are tested with, everywhere they are written.

    python tools/raise_tested.py                    # show what would change
    python tools/raise_tested.py --write            # change it, then relock

An adapter is tested against one exact set of framework versions, the set in its
``tested-with.txt``, and that set is also the minimum the package declares. The versions
are quoted in many places a reader meets them: each adapter's ``pyproject.toml`` and
README, the examples, the documentation and the tests that hold those to each other. This
script moves all of them together, so a raise is one command and one reviewed diff.

For each package in a ``tested-with.txt`` it asks the resolver for the newest release
that is at least seven days old (the cooling-off ``tools/lock.py`` uses), and where that
is newer than the pin it rewrites, across the tracked files:

- ``package==OLD``                       the pin
- ``package>=OLD``                       the declared minimum
- ``PACKAGE_VERSION = "OLD"``            the constant an example checks itself against

``CHANGELOG.md`` is history and is left alone, and ``requirements/`` is regenerated by
``tools/lock.py``, which this runs at the end. Nothing here decides that the new versions
work: the test suite and the pull request lanes do.

Standard library only, Python 3.11+. Needs ``uv`` and ``git`` on PATH.
"""

from __future__ import annotations

import argparse
import datetime
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import lock  # noqa: E402

#: Never rewritten: the changelog is a record, and the locks are generated.
UNTOUCHED = ("CHANGELOG.md", "requirements/")


def tested() -> dict[str, str]:
    """Every package pinned in any ``tested-with.txt`` -> its version (one version each)."""
    pins: dict[str, str] = {}
    for directory in lock.adapter_directories():
        text = (lock.ADAPTERS / directory / "tested-with.txt").read_text(encoding="utf-8")
        for pin in text.split():
            name, version = pin.split("==")
            if pins.setdefault(name, version) != version:
                raise SystemExit(f"{name} is pinned at two versions across the adapters")
    return pins


def newest(pins: dict[str, str], cutoff: str) -> dict[str, str]:
    """The newest release of each package older than the cutoff, resolved per adapter, so
    that packages tested together are raised to versions that install together, and for
    the oldest Python the adapter declares, so that the set installs on every Python it
    claims. A framework release that has dropped that Python is passed over."""
    found: dict[str, str] = {}
    for directory in lock.adapter_directories():
        text = (lock.ADAPTERS / directory / "tested-with.txt").read_text(encoding="utf-8")
        names = [pin.split("==")[0] for pin in text.split()]
        body = lock.resolve(
            names,
            ["--python-version", lock.adapter_python(directory), "--exclude-newer", cutoff],
            directory,
        )
        resolved = {name.lower(): version for name, version in lock.pins(body)}
        for name in names:
            version = resolved[name.lower()]
            if found.setdefault(name, version) != version:
                raise SystemExit(
                    f"{name} resolves to {found[name]} for one adapter and {version} for "
                    f"{directory}; raise them by hand"
                )
    return found


def constant(package: str) -> str:
    """``openai-agents`` -> ``OPENAI_AGENTS_VERSION``; ``pydantic-ai-slim`` drops its suffix."""
    name = package.upper().replace("-", "_")
    return (name[: -len("_SLIM")] if name.endswith("_SLIM") else name) + "_VERSION"


def rewrite(text: str, package: str, old: str, new: str) -> str:
    edge = r"(?<![A-Za-z0-9_.\-])"
    text = re.sub(
        rf"{edge}{re.escape(package)}(==|>=){re.escape(old)}(?!\.?\d)",
        rf"{package}\g<1>{new}",
        text,
    )
    return re.sub(
        rf'\b{constant(package)} = "{re.escape(old)}"', f'{constant(package)} = "{new}"', text
    )


def tracked() -> list[Path]:
    listed = subprocess.run(
        ["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True
    ).stdout.split("\n")
    return [ROOT / name for name in listed if name and not name.startswith(UNTOUCHED)]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write", action="store_true", help="rewrite the files and relock")
    args = parser.parse_args(argv)
    today = datetime.datetime.now(datetime.timezone.utc).date()
    cutoff = (today - datetime.timedelta(days=lock.COOLING_OFF_DAYS)).isoformat() + "T00:00:00Z"
    now = tested()
    target = newest(now, cutoff)
    raises = {name: (now[name], target[name]) for name in sorted(now) if target[name] != now[name]}
    for name in sorted(now):
        mark = f"-> {target[name]}" if name in raises else "(newest that is a week old)"
        print(f"{name}=={now[name]} {mark}")
    if not raises:
        return 0
    changed = 0
    for path in tracked():
        try:
            before = path.read_text(encoding="utf-8")
        except (UnicodeDecodeError, FileNotFoundError):
            continue
        after = before
        for name, (old, new) in raises.items():
            after = rewrite(after, name, old, new)
        if after != before:
            changed += 1
            if args.write:
                path.write_text(after, encoding="utf-8", newline="\n")
            else:
                print(f"  would change {path.relative_to(ROOT).as_posix()}")
    print(f"{changed} file(s) {'changed' if args.write else 'would change'}")
    if args.write:
        return lock.main([])
    return 0


if __name__ == "__main__":
    sys.exit(main())
